//! The app's own configuration (since 0.23.0): `config/app.yaml` and its profiles,
//! `config/app.<profile>.yaml`, become `lib/app.config.g.dart` (beside `output`, as the generated
//! `main()` is), a class of constants:
//!
//! ```yaml
//! # config/app.yaml: the values of every build
//! api:
//!   # The API every call goes to.
//!   base_url: https://api.example.com
//!   timeout_ms: 8000
//! # config/app.dev.yaml: what the profile `dev` changes
//! api:
//!   base_url: http://localhost:8080
//! ```
//!
//! ```dart
//! abstract final class AppConfig {
//!   static const String profile = _profile;
//!   static const String apiBaseUrl = _profile == 'dev' ? 'http://localhost:8080' : 'https://api.example.com';
//!   static const int apiTimeoutMs = 8000;
//! }
//! ```
//!
//! Every value of every profile is in the file, and one compile-time constant picks the profile:
//! `--dart-define=FSP_PROFILE=<name>` (what `fsp dev --profile` and `fsp build --profile` pass),
//! else the flavour (`--flavor`, through Flutter's `FLUTTER_APP_FLAVOR`) when a profile has its
//! name, else `dev` in a debug build when there is a `dev` profile, else `default`, which is
//! `config/app.yaml` alone. The compilers fold the choice, so a release build holds the values
//! of its own profile only, and code under `if (AppConfig.someFlag)` is left out when the flag is
//! false. A `FSP_PROFILE` that names no profile stops the build (a constant division by zero).
//! The output depends on the project's files alone, like `app.g.dart`, and `fsp check` checks
//! it: a profile key that `app.yaml` does not have, a type that differs, a value that looks
//! like a credential ([`crate::secrets`]). The commands of `fsp dev` and `fsp build` get the
//! profile as `FSP_PROFILE` and each value as a `FSP_CONFIG_*` variable ([`task_vars`]).

use std::collections::HashMap;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{Result, bail};
use serde_yaml_ng::Value;

use crate::dart::Span;
use crate::diag::{Base, Diags, Level};
use crate::secrets;

/// The folder of the configuration, relative to the project.
pub const DIR: &str = "config";
/// The file of the values every build has.
pub const BASE_FILE: &str = "config/app.yaml";
/// The compile-time define that names the profile.
pub const DEFINE: &str = "FSP_PROFILE";
/// The profile name of `config/app.yaml` alone.
pub const DEFAULT_PROFILE: &str = "default";
/// The profile a debug build uses when no other is named, when there is one of that name.
pub const DEBUG_PROFILE: &str = "dev";
/// How the generated file starts: a file that starts so and has no `config/app.yaml` beside it
/// is left over.
pub const HEADER: &str = "// GENERATED by fsp from config/";

/// Flutter's build modes, which a profile cannot be named after.
const MODES: [&str; 3] = ["debug", "profile", "release"];

/// Dart's reserved words, which a field cannot be named.
const RESERVED: &[&str] = &[
    "assert", "break", "case", "catch", "class", "const", "continue", "default", "do", "else",
    "enum", "extends", "false", "final", "finally", "for", "if", "in", "is", "new", "null",
    "rethrow", "return", "super", "switch", "this", "throw", "true", "try", "var", "void", "while",
    "with",
];

/// A value as the generated file writes it.
#[derive(Debug, Clone, PartialEq)]
enum Lit {
    Null,
    Str(String),
    Bool(bool),
    Int(i64),
    Double(f64),
    List(Vec<Lit>),
}

/// The type of a value that is not a list, or of a list's items.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Scalar {
    Str,
    Bool,
    Int,
    Double,
}

impl Scalar {
    fn dart(self) -> &'static str {
        match self {
            Scalar::Str => "String",
            Scalar::Bool => "bool",
            Scalar::Int => "int",
            Scalar::Double => "double",
        }
    }

    fn words(self) -> &'static str {
        match self {
            Scalar::Str => "a string",
            Scalar::Bool => "a boolean",
            Scalar::Int | Scalar::Double => "a number",
        }
    }

    /// The type of two values that hold `self` and `other`: an int and a double make a double.
    fn unify(self, other: Scalar) -> Option<Scalar> {
        match (self, other) {
            (a, b) if a == b => Some(a),
            (Scalar::Int, Scalar::Double) | (Scalar::Double, Scalar::Int) => Some(Scalar::Double),
            _ => None,
        }
    }
}

/// The type of a value: a scalar, or a list of scalars (`None` while every list seen is empty).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Ty {
    Scalar(Scalar),
    List(Option<Scalar>),
}

impl Ty {
    fn words(self) -> String {
        match self {
            Ty::Scalar(s) => s.words().to_string(),
            Ty::List(Some(s)) => format!("a list of {}s", s.dart()),
            Ty::List(None) => "an empty list".to_string(),
        }
    }

    fn unify(self, other: Ty) -> Option<Ty> {
        match (self, other) {
            (Ty::Scalar(a), Ty::Scalar(b)) => a.unify(b).map(Ty::Scalar),
            (Ty::List(None), Ty::List(b)) => Some(Ty::List(b)),
            (Ty::List(a), Ty::List(None)) => Some(Ty::List(a)),
            (Ty::List(Some(a)), Ty::List(Some(b))) => a.unify(b).map(|s| Ty::List(Some(s))),
            _ => None,
        }
    }
}

/// One value of the configuration: its path in the YAML, its name in Dart, and its values.
#[derive(Debug, Clone)]
struct Leaf {
    /// The keys, as `config/app.yaml` spells them: `["api", "base_url"]`.
    path: Vec<String>,
    /// The constant: `apiBaseUrl`.
    name: String,
    /// Settled once every file is read.
    ty: Option<Ty>,
    nullable: bool,
    base: Lit,
    /// The profiles that set it, in the order of `profiles`.
    overrides: Vec<(String, Lit)>,
    /// The comment above the key in `config/app.yaml`.
    doc: Vec<String>,
    /// The file that first gave it its type, for a message.
    typed_in: String,
}

/// The configuration of an app, checked: what [`emit`] writes.
#[derive(Debug, Clone)]
pub struct AppConfig {
    /// The profiles, sorted: the `<name>` of each `config/app.<name>.yaml`.
    pub profiles: Vec<String>,
    leaves: Vec<Leaf>,
}

/// What [`load`] found.
#[derive(Debug, Default)]
pub struct Loaded {
    /// Whether the app has a `config/app.yaml`: whether `gen` writes the configuration.
    pub on: bool,
    /// The configuration, when it has no errors.
    pub config: Option<AppConfig>,
    /// Errors and warnings, about files relative to the project.
    pub diags: Diags,
}

/// Where a key is in a file, and the comment above it.
#[derive(Debug, Clone)]
struct KeyAt {
    span: Span,
    doc: Vec<String>,
}

/// One file of `config/`, parsed.
struct Source {
    /// `config/app.staging.yaml`.
    rel: String,
    /// `None` for `config/app.yaml`.
    profile: Option<String>,
    value: Value,
    keys: HashMap<Vec<String>, KeyAt>,
}

impl Source {
    fn span(&self, path: &[String]) -> Option<&Span> {
        self.keys.get(path).map(|k| &k.span)
    }
}

/// The profile names `config/` has, from the file names alone (nothing is parsed), sorted:
/// what `--profile` may name. `None` when there is no `config/app.yaml`.
#[must_use]
pub fn profile_names(project: &Path) -> Option<Vec<String>> {
    let dir = project.join(DIR);
    if !dir.join("app.yaml").is_file() {
        return None;
    }
    let mut names: Vec<String> = fs::read_dir(&dir)
        .ok()?
        .filter_map(Result::ok)
        .filter(|e| e.path().is_file())
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().into_owned();
            name.strip_prefix("app.")
                .and_then(|r| r.strip_suffix(".yaml"))
                .filter(|p| is_profile_name(p))
                .map(str::to_string)
        })
        .collect();
    names.sort();
    Some(names)
}

fn is_profile_name(name: &str) -> bool {
    let mut chars = name.chars();
    chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
}

fn is_key(name: &str) -> bool {
    is_profile_name(name)
}

/// The Dart name of a path: `["api", "base_url"]` is `apiBaseUrl`, `["oidc", "clientId"]` is
/// `oidcClientId`.
fn dart_name(path: &[String]) -> String {
    let mut out = String::new();
    for word in path.iter().flat_map(|k| k.split(['_', '-'])) {
        let mut chars = word.chars();
        let Some(first) = chars.next() else { continue };
        if out.is_empty() {
            out.push(first.to_ascii_lowercase());
        } else {
            out.push(first.to_ascii_uppercase());
        }
        out.extend(chars);
    }
    out
}

/// The variable a key is for the commands of `fsp dev` and `fsp build` (since 0.23.0):
/// `["api", "base_url"]` is `FSP_CONFIG_API_BASE_URL`, `["oidc", "clientId"]`
/// `FSP_CONFIG_OIDC_CLIENT_ID`.
fn var_name(path: &[String]) -> String {
    use heck::ToShoutySnakeCase as _;
    let words: Vec<String> = path.iter().map(|k| k.to_shouty_snake_case()).collect();
    format!("FSP_CONFIG_{}", words.join("_"))
}

/// `api.base_url`, as a message names a key.
fn dotted(path: &[String]) -> String {
    path.join(".")
}

/// Reads and checks `config/`. `output` is where the configuration is generated (`Config::output_config`),
/// for the warning about a file left over from a `config/app.yaml` that is gone.
#[must_use]
pub fn load(project: &Path, output: &str) -> Loaded {
    let mut loaded = Loaded::default();
    let dir = project.join(DIR);
    let mut files: Vec<String> = fs::read_dir(&dir)
        .map(|entries| {
            entries
                .filter_map(Result::ok)
                .filter(|e| e.path().is_file())
                .map(|e| e.file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    files.sort();
    let mut base = false;
    let mut profiles: Vec<String> = vec![];
    let error = |diags: &mut Diags, file: &str, msg: String| {
        diags.add(Level::Error, Base::Project, file, None, msg);
    };
    for name in &files {
        let rel = format!("{DIR}/{name}");
        if name == "app.yaml" {
            base = true;
        } else if name == "app.yml" || (name.starts_with("app.") && name.ends_with(".yml")) {
            let fixed = format!("{}.yaml", name.trim_end_matches(".yml"));
            error(
                &mut loaded.diags,
                &rel,
                format!("fsp reads `.yaml` files in config/: rename {rel} to {DIR}/{fixed}"),
            );
        } else if let Some(p) = name
            .strip_prefix("app.")
            .and_then(|r| r.strip_suffix(".yaml"))
        {
            if p == DEFAULT_PROFILE {
                error(
                    &mut loaded.diags,
                    &rel,
                    format!(
                        "`{DEFAULT_PROFILE}` is the name of config/app.yaml alone, not of a profile: rename {rel}"
                    ),
                );
            } else if MODES.contains(&p) {
                error(
                    &mut loaded.diags,
                    &rel,
                    format!(
                        "`{p}` is a Flutter build mode (`flutter run --{p}`), not a profile: rename {rel}"
                    ),
                );
            } else if !is_profile_name(p) {
                error(
                    &mut loaded.diags,
                    &rel,
                    format!(
                        "`{p}` is not a profile name: use letters, digits, `_` and `-`, starting with a letter (config/app.<profile>.yaml)"
                    ),
                );
            } else if let Some(other) = profiles.iter().find(|o| o.eq_ignore_ascii_case(p)) {
                error(
                    &mut loaded.diags,
                    &rel,
                    format!(
                        "the profiles `{other}` and `{p}` differ only in case, which a file system on macOS or Windows cannot hold: rename one"
                    ),
                );
            } else {
                profiles.push(p.to_string());
            }
        }
    }
    // By name, not by file name: `keycloak` before `keycloak-dpop` (`app.keycloak-dpop.yaml` sorts
    // first, `-` being before `.`).
    profiles.sort();
    if !base {
        if let Some(first) = profiles.first() {
            error(
                &mut loaded.diags,
                &format!("{DIR}/app.{first}.yaml"),
                format!(
                    "{DIR}/app.{first}.yaml is a profile of config/app.yaml, which is missing: a profile changes values that config/app.yaml has"
                ),
            );
        } else if fs::read_to_string(project.join(output))
            .is_ok_and(|text| text.starts_with(HEADER))
        {
            loaded.diags.add(
                Level::Warning,
                Base::Project,
                output,
                None,
                format!("{output} was generated from config/app.yaml, which is gone: delete {output}, or put config/app.yaml back"),
            );
        }
        return loaded;
    }
    loaded.on = true;
    let mut sources = vec![];
    let mut read = |rel: String, profile: Option<String>, diags: &mut Diags| {
        let text = match fs::read_to_string(project.join(&rel)) {
            Ok(t) => t,
            Err(e) => {
                diags.add(
                    Level::Error,
                    Base::Project,
                    &rel,
                    None,
                    format!("cannot read {rel}: {e}"),
                );
                return;
            }
        };
        match serde_yaml_ng::from_str::<Value>(&text) {
            Ok(value) => sources.push(Source {
                keys: index(&text),
                rel,
                profile,
                value,
            }),
            Err(e) => {
                let span = e.location().map(|l| {
                    let at = l.index().min(text.len());
                    Span {
                        line: l.line(),
                        bytes: at..(at + 1).min(text.len()),
                    }
                });
                let msg = e.to_string();
                let msg = msg.split(" at line ").next().unwrap_or(&msg);
                diags.add(
                    Level::Error,
                    Base::Project,
                    &rel,
                    span.as_ref(),
                    format!("{rel} is not YAML that fsp can read: {msg}"),
                );
            }
        }
    };
    read(BASE_FILE.to_string(), None, &mut loaded.diags);
    for p in &profiles {
        read(
            format!("{DIR}/app.{p}.yaml"),
            Some(p.clone()),
            &mut loaded.diags,
        );
    }
    if loaded.diags.has_errors() {
        return loaded;
    }
    let config = build(&sources, profiles, &mut loaded.diags);
    if !loaded.diags.has_errors() {
        loaded.config = config;
    }
    loaded
}

/// Everything after parsing: the keys of `config/app.yaml`, each profile against them, the types,
/// the names and the secrets.
fn build(sources: &[Source], profiles: Vec<String>, diags: &mut Diags) -> Option<AppConfig> {
    let base = &sources[0];
    let Value::Mapping(map) = &base.value else {
        let msg = if base.value.is_null() {
            "config/app.yaml has no values: write `key: value` lines, which `fsp gen` turns into the constants of AppConfig".to_string()
        } else {
            "config/app.yaml must be a map of keys to values (`api_url: https://...`)".to_string()
        };
        diags.add(Level::Error, Base::Project, BASE_FILE, None, msg);
        return None;
    };
    if map.is_empty() {
        diags.add(
            Level::Error,
            Base::Project,
            BASE_FILE,
            None,
            "config/app.yaml has no values: write `key: value` lines, which `fsp gen` turns into the constants of AppConfig",
        );
        return None;
    }
    let mut leaves = vec![];
    walk_base(base, map, &mut vec![], &mut leaves, diags);
    for source in &sources[1..] {
        let profile = source.profile.clone().unwrap_or_default();
        match &source.value {
            Value::Null => {}
            Value::Mapping(m) => {
                walk_profile(source, &profile, m, map, &mut vec![], &mut leaves, diags);
            }
            _ => diags.add(
                Level::Error,
                Base::Project,
                &source.rel,
                None,
                format!(
                    "{} must be a map of the keys of config/app.yaml it changes",
                    source.rel
                ),
            ),
        }
    }
    // Types: every value of a key, in every file, must agree.
    for leaf in &mut leaves {
        settle(leaf, sources, diags);
    }
    // Names: two keys may not make one constant, and none may be a reserved word.
    let mut names: HashMap<String, String> = HashMap::new();
    names.insert("profile".into(), "AppConfig.profile".into());
    for leaf in &leaves {
        let key = dotted(&leaf.path);
        let span = base.span(&leaf.path);
        if RESERVED.contains(&leaf.name.as_str()) {
            diags.add(
                Level::Error,
                Base::Project,
                BASE_FILE,
                span,
                format!("`{key}` would be the constant AppConfig.{}, and `{}` is a reserved word in Dart: rename the key", leaf.name, leaf.name),
            );
        } else if let Some(other) = names.get(&leaf.name) {
            let msg = if other == "AppConfig.profile" {
                format!(
                    "`{key}` would be the constant AppConfig.profile, which is the name of the active profile: rename the key"
                )
            } else {
                format!(
                    "`{key}` and `{other}` would both be the constant AppConfig.{}: rename one",
                    leaf.name
                )
            };
            diags.add(Level::Error, Base::Project, BASE_FILE, span, msg);
        } else {
            names.insert(leaf.name.clone(), key);
        }
    }
    // The variables the task's commands get (since 0.23.0): `apiURL` and `api_url` are two
    // constants but one variable. Two keys that are one constant are said once, above.
    let mut vars: HashMap<String, String> = HashMap::new();
    let named = !diags.has_errors();
    for leaf in leaves.iter().filter(|_| named) {
        let key = dotted(&leaf.path);
        let var = var_name(&leaf.path);
        if let Some(other) = vars.get(&var) {
            diags.add(
                Level::Error,
                Base::Project,
                BASE_FILE,
                base.span(&leaf.path),
                format!("`{key}` and `{other}` would both be the variable {var} of the task's commands: rename one"),
            );
        } else {
            vars.insert(var, key);
        }
    }
    (!diags.has_errors()).then_some(AppConfig { profiles, leaves })
}

/// The keys of `config/app.yaml` below `path`: a map is a group, anything else a value.
fn walk_base(
    source: &Source,
    map: &serde_yaml_ng::Mapping,
    path: &mut Vec<String>,
    leaves: &mut Vec<Leaf>,
    diags: &mut Diags,
) {
    for (k, v) in map {
        let Some(key) = key_of(source, k, path, diags) else {
            continue;
        };
        path.push(key);
        let span = source.span(path).cloned();
        match v {
            Value::Mapping(inner) if inner.is_empty() => diags.add(
                Level::Error,
                Base::Project,
                &source.rel,
                span.as_ref(),
                format!(
                    "`{}` is an empty map: give it keys, or remove it",
                    dotted(path)
                ),
            ),
            Value::Mapping(inner) => walk_base(source, inner, path, leaves, diags),
            other => {
                if let Some(lit) = literal(source, path, other, diags) {
                    check_secret(source, path, &lit, diags);
                    leaves.push(Leaf {
                        path: path.clone(),
                        name: dart_name(path),
                        ty: None,
                        nullable: false,
                        base: lit,
                        overrides: vec![],
                        doc: source
                            .keys
                            .get(path.as_slice())
                            .map(|k| k.doc.clone())
                            .unwrap_or_default(),
                        typed_in: String::new(),
                    });
                }
            }
        }
        path.pop();
    }
}

/// The keys of a profile below `path`, each of which `config/app.yaml` must have.
fn walk_profile(
    source: &Source,
    profile: &str,
    map: &serde_yaml_ng::Mapping,
    base: &serde_yaml_ng::Mapping,
    path: &mut Vec<String>,
    leaves: &mut [Leaf],
    diags: &mut Diags,
) {
    for (k, v) in map {
        let Some(key) = key_of(source, k, path, diags) else {
            continue;
        };
        path.push(key.clone());
        let span = source.span(path).cloned();
        let error = |diags: &mut Diags, msg: String| {
            diags.add(Level::Error, Base::Project, &source.rel, span.as_ref(), msg);
        };
        match (base.get(key.as_str()), v) {
            (None, _) => error(
                diags,
                format!(
                    "`{}` is not in config/app.yaml: a profile only changes values that config/app.yaml has (a typo?)",
                    dotted(path)
                ),
            ),
            (Some(Value::Mapping(inner)), Value::Mapping(mine)) => {
                walk_profile(source, profile, mine, inner, path, leaves, diags);
            }
            (Some(Value::Mapping(_)), _) => error(
                diags,
                format!(
                    "`{}` is a map in config/app.yaml: {} can change the values in it, not replace it",
                    dotted(path),
                    source.rel
                ),
            ),
            (Some(_), Value::Mapping(_)) => error(
                diags,
                format!(
                    "`{}` is a value in config/app.yaml, not a map",
                    dotted(path)
                ),
            ),
            (Some(_), other) => {
                if let Some(lit) = literal(source, path, other, diags) {
                    check_secret(source, path, &lit, diags);
                    if let Some(leaf) = leaves.iter_mut().find(|l| l.path == *path) {
                        leaf.overrides.push((profile.to_string(), lit));
                    }
                }
            }
        }
        path.pop();
    }
}

/// A key of a map, which must be a string fit for a Dart name.
fn key_of(source: &Source, k: &Value, path: &[String], diags: &mut Diags) -> Option<String> {
    let Some(key) = k.as_str() else {
        let shown = crate::config::shown_value(k);
        let at = if path.is_empty() {
            String::new()
        } else {
            format!(" in `{}`", dotted(path))
        };
        diags.add(
            Level::Error,
            Base::Project,
            &source.rel,
            None,
            format!("`{shown}`{at} is not a key fsp can name: a key is letters, digits, `_` and `-`, starting with a letter"),
        );
        return None;
    };
    if !is_key(key) {
        let mut full = path.to_vec();
        full.push(key.to_string());
        diags.add(
            Level::Error,
            Base::Project,
            &source.rel,
            source.span(&full),
            format!("`{}` is not a key fsp can name: a key is letters, digits, `_` and `-`, starting with a letter", dotted(&full)),
        );
        return None;
    }
    Some(key.to_string())
}

/// 2^53: the largest integer a double holds exactly, which is what an `int` is on the web.
const WEB_INT: i64 = 1 << 53;

/// A value of a file as the generated file will write it, or an error about it.
fn literal(source: &Source, path: &[String], v: &Value, diags: &mut Diags) -> Option<Lit> {
    let error = |diags: &mut Diags, msg: String| {
        diags.add(
            Level::Error,
            Base::Project,
            &source.rel,
            source.span(path),
            msg,
        );
    };
    let key = dotted(path);
    let scalar = |v: &Value, diags: &mut Diags| -> Option<Lit> {
        match v {
            Value::Bool(b) => Some(Lit::Bool(*b)),
            Value::String(s) => Some(Lit::Str(s.clone())),
            Value::Number(n) => {
                if let Some(i) = n.as_i64() {
                    if i.abs() > WEB_INT {
                        error(
                            diags,
                            format!(
                                "`{key}` is {i}, more than an int holds exactly on the web (2^53): write it as a string"
                            ),
                        );
                        return None;
                    }
                    Some(Lit::Int(i))
                } else if n.as_u64().is_some() {
                    error(
                        diags,
                        format!(
                            "`{key}` is {n}, more than an int holds exactly on the web (2^53): write it as a string"
                        ),
                    );
                    None
                } else {
                    let f = n.as_f64().unwrap_or(f64::NAN);
                    if f.is_finite() {
                        Some(Lit::Double(f))
                    } else {
                        error(
                            diags,
                            format!("`{key}` is {n}, which is not a finite number"),
                        );
                        None
                    }
                }
            }
            _ => None,
        }
    };
    match v {
        Value::Null => Some(Lit::Null),
        Value::Sequence(items) => {
            let mut out = vec![];
            for item in items {
                match scalar(item, diags) {
                    Some(lit) => out.push(lit),
                    None if matches!(item, Value::Number(_)) => return None,
                    None => {
                        error(
                            diags,
                            format!(
                                "`{key}` is a list of {}: a list holds strings, numbers or booleans",
                                kind_words(item)
                            ),
                        );
                        return None;
                    }
                }
            }
            Some(Lit::List(out))
        }
        Value::Tagged(t) => {
            error(
                diags,
                format!(
                    "`{key}` has the tag `{}`, which fsp does not read: write the value alone",
                    t.tag
                ),
            );
            None
        }
        other => scalar(other, diags),
    }
}

fn kind_words(v: &Value) -> &'static str {
    match v {
        Value::Null => "nulls",
        Value::Sequence(_) => "lists",
        Value::Mapping(_) => "maps",
        _ => "values",
    }
}

fn lit_ty(lit: &Lit) -> Result<Option<Ty>, (Scalar, Scalar)> {
    let scalar = |l: &Lit| match l {
        Lit::Str(_) => Some(Scalar::Str),
        Lit::Bool(_) => Some(Scalar::Bool),
        Lit::Int(_) => Some(Scalar::Int),
        Lit::Double(_) => Some(Scalar::Double),
        Lit::Null | Lit::List(_) => None,
    };
    match lit {
        Lit::Null => Ok(None),
        Lit::List(items) => {
            let mut ty: Option<Scalar> = None;
            for item in items {
                let Some(s) = scalar(item) else { continue };
                ty = match ty {
                    None => Some(s),
                    Some(t) => Some(t.unify(s).ok_or((t, s))?),
                };
            }
            Ok(Some(Ty::List(ty)))
        }
        other => Ok(scalar(other).map(Ty::Scalar)),
    }
}

/// Settles the type of `leaf` from all its values, or says where they disagree.
fn settle(leaf: &mut Leaf, sources: &[Source], diags: &mut Diags) {
    let key = dotted(&leaf.path);
    let values: Vec<(String, Lit)> = std::iter::once((BASE_FILE.to_string(), leaf.base.clone()))
        .chain(
            leaf.overrides
                .iter()
                .map(|(p, l)| (format!("{DIR}/app.{p}.yaml"), l.clone())),
        )
        .collect();
    let span_in = |rel: &str| {
        sources
            .iter()
            .find(|s| s.rel == rel)
            .and_then(|s| s.span(&leaf.path))
            .cloned()
    };
    for (rel, lit) in &values {
        if *lit == Lit::Null {
            leaf.nullable = true;
            continue;
        }
        let ty = match lit_ty(lit) {
            Ok(Some(t)) => t,
            Ok(None) => continue,
            Err((a, b)) => {
                diags.add(
                    Level::Error,
                    Base::Project,
                    rel,
                    span_in(rel).as_ref(),
                    format!(
                        "`{key}` holds {} and {}: a list holds one type",
                        a.words(),
                        b.words()
                    ),
                );
                return;
            }
        };
        match leaf.ty {
            None => {
                leaf.ty = Some(ty);
                leaf.typed_in.clone_from(rel);
            }
            Some(have) => {
                let Some(t) = have.unify(ty) else {
                    diags.add(
                        Level::Error,
                        Base::Project,
                        rel,
                        span_in(rel).as_ref(),
                        format!(
                            "`{key}` is {} in {} and {} in {rel}: a key has one type in every file",
                            have.words(),
                            leaf.typed_in,
                            ty.words()
                        ),
                    );
                    return;
                };
                leaf.ty = Some(t);
            }
        }
    }
    match leaf.ty {
        None => diags.add(
            Level::Error,
            Base::Project,
            BASE_FILE,
            span_in(BASE_FILE).as_ref(),
            format!("`{key}` is null in config/app.yaml and in every profile, so fsp cannot tell its type: give it a value in one of them"),
        ),
        Some(Ty::List(None)) => diags.add(
            Level::Error,
            Base::Project,
            BASE_FILE,
            span_in(BASE_FILE).as_ref(),
            format!("`{key}` is an empty list in every file, so fsp cannot tell what it holds: give it a value in one of them"),
        ),
        Some(_) => {}
    }
}

/// The error for a value that looks like a credential, and the warnings for a key named like a
/// secret and a JWT.
fn check_secret(source: &Source, path: &[String], lit: &Lit, diags: &mut Diags) {
    let key = dotted(path);
    let strings: Vec<&str> = match lit {
        Lit::Str(s) => vec![s.as_str()],
        Lit::List(items) => items
            .iter()
            .filter_map(|l| match l {
                Lit::Str(s) => Some(s.as_str()),
                _ => None,
            })
            .collect(),
        _ => vec![],
    };
    let span = source.span(path);
    for s in &strings {
        if let Some(what) = secrets::looks_like(s) {
            diags.add(
                Level::Error,
                Base::Project,
                &source.rel,
                span,
                format!("`{key}` in {} looks like {what}: every value in config/ is compiled into the app, where anyone who has the app can read it; keep the secret on a server and give the app only what it may show (docs/app-config.md, \"Secrets\")", source.rel),
            );
            return;
        }
    }
    let leaf = path.last().map_or("", String::as_str);
    if secrets::named_like(leaf) && strings.iter().any(|s| !s.is_empty()) {
        diags.add(
            Level::Warning,
            Base::Project,
            &source.rel,
            span,
            format!("`{key}` in {} is named like a secret: every value in config/ is compiled into the app, where anyone who has the app can read it; if it is a secret, keep it on a server (docs/app-config.md, \"Secrets\"), and if it is not, give it a name that says so", source.rel),
        );
    } else if strings
        .iter()
        .any(|s| secrets::is_jwt(s) && !secrets::is_public_jwt(s))
    {
        diags.add(
            Level::Warning,
            Base::Project,
            &source.rel,
            span,
            format!("`{key}` in {} is a JWT: every value in config/ is compiled into the app, where anyone who has the app can read it; if the token grants access, keep it on a server (docs/app-config.md, \"Secrets\")", source.rel),
        );
    }
}

