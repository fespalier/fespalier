/// A Dart string literal.
fn dart_string(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 || c == '\u{7f}' => {
                let _ = write!(out, "\\u{{{:x}}}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

fn dart_lit(lit: &Lit, ty: Ty) -> String {
    match lit {
        Lit::Null => "null".to_string(),
        Lit::Str(s) => dart_string(s),
        Lit::Bool(b) => b.to_string(),
        Lit::Int(i) if ty == Ty::Scalar(Scalar::Double) || ty == Ty::List(Some(Scalar::Double)) => {
            format!("{i}.0")
        }
        Lit::Int(i) => i.to_string(),
        Lit::Double(f) => format!("{f:?}"),
        Lit::List(items) => {
            let inner: Vec<String> = items.iter().map(|i| dart_lit(i, ty)).collect();
            format!("[{}]", inner.join(", "))
        }
    }
}

fn dart_type(ty: Ty, nullable: bool) -> String {
    let base = match ty {
        Ty::Scalar(s) => s.dart().to_string(),
        Ty::List(s) => format!("List<{}>", s.unwrap_or(Scalar::Str).dart()),
    };
    if nullable { format!("{base}?") } else { base }
}

/// `lib/app.config.g.dart` for `config`.
#[must_use]
pub fn emit(config: &AppConfig) -> String {
    let mut files = vec![BASE_FILE.to_string()];
    files.extend(
        config
            .profiles
            .iter()
            .map(|p| format!("{DIR}/app.{p}.yaml")),
    );
    let sources = match files.as_slice() {
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
        [] => String::new(),
    };
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}: edit {sources}, not this file.");
    out.push_str("// Every value here is compiled into the app, where anyone who has the app can read it: never a\n");
    out.push_str("// secret (docs/app-config.md).\n");
    out.push_str("// ignore_for_file: type=lint, unused_element\n\n");

    let profiles = &config.profiles;
    let has_dev = profiles.iter().any(|p| p == DEBUG_PROFILE);
    let names: Vec<String> = std::iter::once(DEFAULT_PROFILE.to_string())
        .chain(profiles.iter().cloned())
        .collect();
    let quoted = |p: &str| dart_string(p);
    out.push_str("const String _requested = String.fromEnvironment('FSP_PROFILE');\n");
    if !profiles.is_empty() {
        out.push_str("const String _flavor = String.fromEnvironment('FLUTTER_APP_FLAVOR');\n");
    }
    if has_dev {
        out.push_str("const bool _debug =\n    !bool.fromEnvironment('dart.vm.product') &&\n    !bool.fromEnvironment('dart.vm.profile');\n");
    }
    out.push('\n');
    out.push_str("/// The active profile: FSP_PROFILE (`fsp dev --profile`, `fsp build --profile`), else the\n");
    out.push_str("/// flavour (`--flavor`) when a profile has its name, else `dev` in a debug build when there is\n");
    out.push_str("/// a `dev` profile, else `default`.\n");
    out.push_str("const String _profile = bool.hasEnvironment('FSP_PROFILE')\n");
    out.push_str("    ? (_requested == '' ? 'default' : _requested)\n");
    if !profiles.is_empty() {
        let flavors: Vec<String> = profiles
            .iter()
            .map(|p| format!("_flavor == {}", quoted(p)))
            .collect();
        let _ = writeln!(out, "    : {}\n    ? _flavor", flavors.join(" || "));
    }
    if has_dev {
        let _ = writeln!(out, "    : _debug\n    ? {}", quoted(DEBUG_PROFILE));
    }
    let _ = writeln!(out, "    : {};\n", quoted(DEFAULT_PROFILE));

    let known: Vec<String> = names
        .iter()
        .map(|p| format!("_profile == {}", quoted(p)))
        .collect();
    let listed = names
        .iter()
        .map(|p| format!("`{p}`"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "/// A build whose FSP_PROFILE names no profile of config/ stops here, since dividing by zero is an\n/// error in a constant. The profiles: {listed}."
    );
    let check = format!("({} ? 1 : 0)", known.join(" || "));
    let one_line = format!("const int _fspProfileNamesNoFileOfConfig = 1 ~/ {check};");
    if one_line.chars().count() <= 80 {
        let _ = writeln!(out, "{one_line}\n");
    } else if check.chars().count() + 4 <= 80 {
        let _ = writeln!(
            out,
            "const int _fspProfileNamesNoFileOfConfig =\n    1 ~/ {check};\n"
        );
    } else {
        let _ = writeln!(
            out,
            "const int _fspProfileNamesNoFileOfConfig =\n    1 ~/\n    ({}\n        ? 1\n        : 0);\n",
            known.join(" || ")
        );
    }

    out.push_str(
        "/// The values of config/app.yaml, with those of the active profile over them.\n",
    );
    out.push_str("abstract final class AppConfig {\n");
    let _ = writeln!(
        out,
        "  /// The active profile: {}.",
        or_list(
            &names
                .iter()
                .map(|p| {
                    if p == DEFAULT_PROFILE {
                        format!("`{p}` (config/app.yaml alone)")
                    } else {
                        format!("`{p}`")
                    }
                })
                .collect::<Vec<_>>()
        )
    );
    out.push_str("  static const String profile = _profile;\n");
    for leaf in &config.leaves {
        let ty = leaf.ty.unwrap_or(Ty::Scalar(Scalar::Str));
        out.push('\n');
        for line in &leaf.doc {
            if line.is_empty() {
                out.push_str("  ///\n");
            } else {
                let _ = writeln!(out, "  /// {line}");
            }
        }
        if !leaf.doc.is_empty() {
            out.push_str("  ///\n");
        }
        let mut origin = format!("`{}` in config/app.yaml", dotted(&leaf.path));
        if !leaf.overrides.is_empty() {
            let set: Vec<String> = leaf
                .overrides
                .iter()
                .map(|(p, _)| format!("`{p}`"))
                .collect();
            let _ = write!(origin, "; set by {}", and_list(&set));
        }
        let _ = writeln!(out, "  /// {origin}.");
        let decl = format!(
            "  static const {} {} =",
            dart_type(ty, leaf.nullable),
            leaf.name
        );
        let mut chain = String::new();
        for (p, lit) in &leaf.overrides {
            let _ = write!(
                chain,
                "_profile == {} ? {} : ",
                quoted(p),
                dart_lit(lit, ty)
            );
        }
        let one_line = format!("{decl} {chain}{};", dart_lit(&leaf.base, ty));
        // One line when it fits, as `dart format` leaves it; else a line per branch.
        if leaf.overrides.is_empty() || one_line.chars().count() <= 80 {
            let _ = writeln!(out, "{one_line}");
        } else {
            let _ = writeln!(out, "{decl} _profile == {}", quoted(&leaf.overrides[0].0));
            let _ = writeln!(out, "      ? {}", dart_lit(&leaf.overrides[0].1, ty));
            for (p, lit) in &leaf.overrides[1..] {
                let _ = writeln!(out, "      : _profile == {}", quoted(p));
                let _ = writeln!(out, "      ? {}", dart_lit(lit, ty));
            }
            let _ = writeln!(out, "      : {};", dart_lit(&leaf.base, ty));
        }
    }
    out.push_str("}\n");
    out
}

fn or_list(items: &[String]) -> String {
    match items {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} or {last}", rest.join(", ")),
    }
}

fn and_list(items: &[String]) -> String {
    match items {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

