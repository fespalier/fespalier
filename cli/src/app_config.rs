/// The profile `--profile` names, checked against the files of `config/` before anything runs.
pub fn check_profile(project: &Path, name: &str) -> Result<()> {
    check_named(project, name, &format!("--profile {name}"))
}

/// [`check_profile`] for a profile that `how` names: `--profile staging`, or the define after `--`.
fn check_named(project: &Path, name: &str, how: &str) -> Result<()> {
    let Some(profiles) = profile_names(project) else {
        bail!(
            "`{how}`: this app has no config/app.yaml, so it has no profiles (docs/app-config.md)"
        );
    };
    if name.is_empty() || name == DEFAULT_PROFILE || profiles.iter().any(|p| p == name) {
        return Ok(());
    }
    if MODES.contains(&name) {
        bail!(
            "`{how}` names a profile of config/, and `{name}` is a Flutter build mode: pass that to flutter after `--` (`-- --{name}`)"
        );
    }
    let mut all = vec![DEFAULT_PROFILE.to_string()];
    all.extend(profiles);
    bail!(
        "`{how}`: there is no config/app.{name}.yaml; the profiles are {}",
        all.join(", ")
    )
}

/// A `--dart-define=FSP_PROFILE=<name>` (or `--dart-define FSP_PROFILE=<name>`) in flutter's
/// arguments: the profile named by hand.
#[must_use]
pub fn defined_in(args: &[String]) -> Option<String> {
    let prefix = format!("{DEFINE}=");
    let mut it = args.iter().peekable();
    let mut found = None;
    while let Some(a) = it.next() {
        let value = if let Some(v) = a.strip_prefix("--dart-define=") {
            Some(v.to_string())
        } else if a == "--dart-define" {
            it.peek().map(|v| (*v).clone())
        } else {
            None
        };
        if let Some(v) = value.and_then(|v| v.strip_prefix(&prefix).map(str::to_string)) {
            found = Some(v);
        }
    }
    found
}

/// The `--flavor` in flutter's arguments.
fn flavor_in(args: &[String]) -> Option<String> {
    let mut it = args.iter();
    let mut found = None;
    while let Some(a) = it.next() {
        if let Some(v) = a.strip_prefix("--flavor=") {
            found = Some(v.to_string());
        } else if a == "--flavor" {
            found = it.next().cloned();
        }
    }
    found
}

/// `flutter: default-flavor:` of the pubspec, which Flutter uses when no `--flavor` is given.
#[must_use]
pub fn default_flavor(project: &Path) -> Option<String> {
    let text = fs::read_to_string(project.join("pubspec.yaml")).ok()?;
    let yaml: Value = serde_yaml_ng::from_str(&text).ok()?;
    yaml.get("flutter")?
        .get("default-flavor")?
        .as_str()
        .map(str::to_string)
}

/// The profile a build will have, and why: what the generated `_profile` computes, from what
/// `fsp` can see of the build (since 0.23.0). `explicit` is `--profile` or a define in the
/// arguments; `debug` whether the build is a debug build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Active {
    pub name: String,
    pub why: &'static str,
}

#[must_use]
pub fn active(
    explicit: Option<&str>,
    flutter_args: &[String],
    default_flavor: Option<&str>,
    profiles: &[String],
    debug: bool,
) -> Active {
    if let Some(p) = explicit {
        let name = if p.is_empty() { DEFAULT_PROFILE } else { p };
        return Active {
            name: name.to_string(),
            why: "FSP_PROFILE",
        };
    }
    if let Some(f) = flavor_in(flutter_args).or_else(|| default_flavor.map(str::to_string))
        && profiles.contains(&f)
    {
        return Active {
            name: f,
            why: "the flavour",
        };
    }
    if debug && profiles.iter().any(|p| p == DEBUG_PROFILE) {
        return Active {
            name: DEBUG_PROFILE.to_string(),
            why: "a debug build",
        };
    }
    Active {
        name: DEFAULT_PROFILE.to_string(),
        why: "",
    }
}

impl Active {
    /// `profile staging (FSP_PROFILE): config/app.staging.yaml over config/app.yaml`, or
    /// `profile default: config/app.yaml`.
    #[must_use]
    pub fn line(&self) -> String {
        if self.name == DEFAULT_PROFILE {
            return format!("profile {DEFAULT_PROFILE}: {BASE_FILE}");
        }
        format!(
            "profile {} ({}): {DIR}/app.{}.yaml over {BASE_FILE}",
            self.name, self.why, self.name
        )
    }
}

/// The arguments for flutter with the profile `--profile` names in front of the user's: what
/// `fsp dev` and `fsp build` pass. A define of the user's for it too is an error.
pub fn with_define(profile: Option<&str>, args: &[String]) -> Result<Vec<String>> {
    let Some(p) = profile else {
        return Ok(args.to_vec());
    };
    if let Some(theirs) = defined_in(args) {
        bail!(
            "`--profile {p}` and `--dart-define={DEFINE}={theirs}` after `--` both name the profile: keep one"
        );
    }
    let mut out = vec![format!("--dart-define={DEFINE}={p}")];
    out.extend(args.iter().cloned());
    Ok(out)
}

/// A value as a variable of the task's commands holds it: a string as it is, a number and a boolean
/// as Dart writes them, a list as JSON. `None` for null: the variable is not set.
fn var_value(lit: &Lit, ty: Ty) -> Option<String> {
    let json = |l: &Lit| match l {
        Lit::Str(s) => serde_json::Value::String(s.clone()),
        Lit::Bool(b) => serde_json::Value::Bool(*b),
        Lit::Int(i) => serde_json::Value::from(*i),
        Lit::Double(f) => serde_json::Value::from(*f),
        Lit::Null | Lit::List(_) => serde_json::Value::Null,
    };
    match lit {
        Lit::Null => None,
        Lit::Str(s) => Some(s.clone()),
        Lit::List(items) => {
            Some(serde_json::Value::Array(items.iter().map(json).collect()).to_string())
        }
        other => Some(dart_lit(other, ty)),
    }
}

/// The values of the profile `name` as variables for the commands of `fsp dev` and `fsp build`
/// (`before`, `with`, `run`, `after`; since 0.23.0): `api.base_url` is `FSP_CONFIG_API_BASE_URL`.
/// They are the values when the command starts: a command that runs on is not told of a change.
#[must_use]
pub fn task_vars(config: &AppConfig, name: &str) -> Vec<(String, String)> {
    config
        .leaves
        .iter()
        .filter_map(|leaf| {
            let lit = leaf
                .overrides
                .iter()
                .find(|(p, _)| p == name)
                .map_or(&leaf.base, |(_, lit)| lit);
            let ty = leaf.ty.unwrap_or(Ty::Scalar(Scalar::Str));
            var_value(lit, ty).map(|v| (var_name(&leaf.path), v))
        })
        .collect()
}

/// For `fsp dev` and `fsp build`: the profile line and the `FSP_PROFILE` variable for the task's
/// commands, when the app has a configuration. `debug` is whether the build is a debug build.
/// The variables of the task's commands for the build `active` will be (since 0.23.0):
/// `FSP_PROFILE` and a `FSP_CONFIG_*` per value. A configuration with errors gives `FSP_PROFILE`
/// alone (the generation that runs first reports them).
#[must_use]
pub fn run_vars(project: &Path, output: &str, active: &Active) -> Vec<(String, String)> {
    let mut vars = vec![(DEFINE.to_string(), active.name.clone())];
    if let Some(config) = load(project, output).config {
        vars.extend(task_vars(&config, &active.name));
    }
    vars
}

pub fn for_run(
    project: &Path,
    profile: Option<&str>,
    args: &[String],
    debug: bool,
) -> Result<Option<Active>> {
    if let Some(p) = profile {
        check_profile(project, p)?;
    }
    let Some(profiles) = profile_names(project) else {
        return Ok(None);
    };
    let explicit = profile.map(str::to_string).or_else(|| defined_in(args));
    if let Some(p) = explicit.as_deref().filter(|_| profile.is_none()) {
        check_named(project, p, &format!("--dart-define={DEFINE}={p}"))?;
    }
    let flavor = default_flavor(project);
    Ok(Some(active(
        explicit.as_deref(),
        args,
        flavor.as_deref(),
        &profiles,
        debug,
    )))
}

/// Whether `fsp dev`'s flutter run is a debug build: not with `--release` or `--profile` after `--`.
#[must_use]
pub fn run_is_debug(args: &[String]) -> bool {
    !args.iter().any(|a| a == "--release" || a == "--profile")
}

/// Whether `fsp build`'s flutter build is a debug build: only with `--debug` after `--`.
#[must_use]
pub fn build_is_debug(args: &[String]) -> bool {
    args.iter().any(|a| a == "--debug")
}
