/// Where each key of a block-style YAML file is, and the comment lines right above it. A key in
/// a flow map (`{a: 1}`) or a list item is not indexed: its messages have no code frame.
fn index(text: &str) -> HashMap<Vec<String>, KeyAt> {
    let mut out = HashMap::new();
    let mut stack: Vec<(usize, String)> = vec![];
    let mut doc: Vec<String> = vec![];
    let mut block: Option<usize> = None;
    let mut offset = 0;
    for (n, line) in text.split_inclusive('\n').enumerate() {
        let start = offset;
        offset += line.len();
        let content = line.trim_end_matches(['\n', '\r']);
        let trimmed = content.trim_start();
        let indent = content.len() - trimmed.len();
        if let Some(b) = block {
            if trimmed.is_empty() || indent > b {
                continue;
            }
            block = None;
        }
        if trimmed.is_empty() {
            doc.clear();
            continue;
        }
        if let Some(comment) = trimmed.strip_prefix('#') {
            doc.push(
                comment
                    .strip_prefix(' ')
                    .unwrap_or(comment)
                    .trim_end()
                    .to_string(),
            );
            continue;
        }
        if trimmed.starts_with('-') || trimmed.starts_with("---") || trimmed.starts_with("...") {
            doc.clear();
            continue;
        }
        let Some((key, key_len, rest)) = key_on(trimmed) else {
            doc.clear();
            continue;
        };
        while stack.last().is_some_and(|(i, _)| *i >= indent) {
            stack.pop();
        }
        stack.push((indent, key));
        let path: Vec<String> = stack.iter().map(|(_, k)| k.clone()).collect();
        let at = start + indent;
        out.insert(
            path,
            KeyAt {
                span: Span {
                    line: n + 1,
                    bytes: at..at + key_len,
                },
                doc: std::mem::take(&mut doc),
            },
        );
        let value = rest.split(" #").next().unwrap_or("").trim();
        if value.starts_with('|') || value.starts_with('>') {
            block = Some(indent);
        }
    }
    out
}

/// The key a line starts with, its length in the line, and what follows the `:`.
fn key_on(line: &str) -> Option<(String, usize, &str)> {
    if let Some(q) = line.chars().next().filter(|c| *c == '"' || *c == '\'') {
        let close = line[1..].find(q)? + 1;
        let rest = line[close + 1..].strip_prefix(':')?;
        if !(rest.is_empty() || rest.starts_with([' ', '\t'])) {
            return None;
        }
        return Some((line[1..close].to_string(), close + 1, rest));
    }
    for (i, c) in line.char_indices() {
        if c == ':' {
            let rest = &line[i + 1..];
            if rest.is_empty() || rest.starts_with([' ', '\t']) {
                let key = line[..i].trim_end();
                if key.is_empty() || key.contains(['{', '[', '#']) {
                    return None;
                }
                return Some((key.to_string(), key.len(), rest));
            }
        }
        if c == '#' || c == '{' || c == '[' {
            return None;
        }
    }
    None
}

