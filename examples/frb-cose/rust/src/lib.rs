//! The Rust core of fespalier's `frb-cose` example.
//!
//! The core is `CrateStack`'s generated client of the example's schema (`server/schema.cstack`), on the
//! `cratestack-client` facade with its `cose` feature. Every call is sealed as `COSE_Sign1` and its answer is
//! opened. The device key is not here: the core asks a callback, which Dart answers (`core::signer`).
//!
//! - `core/` is the engine. It is pure Rust and has no `flutter_rust_bridge` type in it.
//! - `api/` is the surface that `flutter_rust_bridge_codegen` generates Dart for. `frb_generated.rs` and
//!   `lib/src/rust/` are generated from it: never edit them.

pub mod api;
pub mod core;

